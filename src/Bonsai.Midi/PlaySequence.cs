using System;
using System.Collections.Generic;
using System.ComponentModel;
using System.Linq;
using System.Reactive;
using System.Reactive.Disposables;
using System.Reactive.Linq;
using System.Xml;
using System.Xml.Serialization;
using Melanchall.DryWetMidi.Common;
using Melanchall.DryWetMidi.Core;
using Melanchall.DryWetMidi.Interaction;

namespace Bonsai.Midi
{
    /// <summary>
    /// Represents an operator that plays back MIDI sequences, emitting each event
    /// when its scheduled time is reached on the specified clock.
    /// </summary>
    /// <remarks>
    /// Playback timing is driven entirely by the clock sequence, and all events are
    /// emitted on the clock thread. Sequence players sharing the same clock are
    /// therefore always synchronized with each other. Receiving a new sequence stops
    /// the current one, releasing any active notes, and starts the new sequence on
    /// the next clock tick, or on the next multiple of <see cref="LaunchQuantization"/>
    /// in clock time, if specified.
    /// </remarks>
    [Combinator]
    [WorkflowElementCategory(ElementCategory.Combinator)]
    [Description("Plays back MIDI sequences, emitting each event when its scheduled time is reached on the specified clock.")]
    public class PlaySequence
    {
        /// <summary>
        /// Gets or sets the interval in clock time to which the start of each sequence
        /// is aligned. If zero, sequences start on the next clock tick.
        /// </summary>
        [XmlIgnore]
        [Description("The interval in clock time to which the start of each sequence is aligned. If zero, sequences start on the next clock tick.")]
        public TimeSpan LaunchQuantization { get; set; }

        /// <summary>
        /// Gets or sets an XML representation of the launch quantization interval for serialization.
        /// </summary>
        [Browsable(false)]
        [XmlElement(nameof(LaunchQuantization))]
        public string LaunchQuantizationXml
        {
            get => XmlConvert.ToString(LaunchQuantization);
            set => LaunchQuantization = XmlConvert.ToTimeSpan(value);
        }

        /// <summary>
        /// Plays back each MIDI file in an observable sequence, emitting its events
        /// as they are reached on the specified clock.
        /// </summary>
        /// <param name="source">A sequence of <see cref="MidiFile"/> objects to play.</param>
        /// <param name="clock">
        /// A sequence of elapsed time values used to drive playback, such as the
        /// ticks generated by <see cref="SequencerClock"/>.
        /// </param>
        /// <returns>A sequence of <see cref="MidiEvent"/> objects in playback order.</returns>
        public IObservable<MidiEvent> Process(IObservable<MidiFile> source, IObservable<TimeSpan> clock)
        {
            return Play(source.Select(ToScheduledEvents), clock);
        }

        static ScheduledEvent[] ToScheduledEvents(MidiFile file)
        {
            var tempoMap = file.GetTempoMap();
            return file.GetTimedEvents()
                .Where(timedEvent => timedEvent.Event is not MetaEvent)
                .Select(timedEvent => new ScheduledEvent(timedEvent.TimeAs<MetricTimeSpan>(tempoMap), timedEvent.Event))
                .OrderBy(scheduledEvent => scheduledEvent.Time)
                .ToArray();
        }

        IObservable<MidiEvent> Play(IObservable<ScheduledEvent[]> source, IObservable<TimeSpan> clock)
        {
            return Observable.Create<MidiEvent>(observer =>
            {
                var gate = new object();
                var sourceCompleted = false;
                ScheduledEvent[]? pending = null;
                ScheduledEvent[]? current = null;
                var index = 0;
                var startTime = TimeSpan.Zero;
                var activeNotes = new HashSet<(FourBitNumber, SevenBitNumber)>();
                var quantization = LaunchQuantization;

                void ReleaseActiveNotes()
                {
                    foreach (var (channel, noteNumber) in activeNotes)
                    {
                        observer.OnNext(new NoteOffEvent(noteNumber, SevenBitNumber.MinValue) { Channel = channel });
                    }
                    activeNotes.Clear();
                }

                void Emit(MidiEvent midiEvent)
                {
                    switch (midiEvent)
                    {
                        case NoteOnEvent noteOn when noteOn.Velocity > 0:
                            activeNotes.Add((noteOn.Channel, noteOn.NoteNumber));
                            break;
                        case NoteOnEvent noteOn:
                            activeNotes.Remove((noteOn.Channel, noteOn.NoteNumber));
                            break;
                        case NoteOffEvent noteOff:
                            activeNotes.Remove((noteOff.Channel, noteOff.NoteNumber));
                            break;
                    }
                    observer.OnNext(midiEvent);
                }

                var sourceObserver = Observer.Create<ScheduledEvent[]>(
                    events =>
                    {
                        lock (gate) pending = events;
                    },
                    error =>
                    {
                        lock (gate) observer.OnError(error);
                    },
                    () =>
                    {
                        lock (gate) sourceCompleted = true;
                    });

                var clockObserver = Observer.Create<TimeSpan>(
                    now =>
                    {
                        lock (gate)
                        {
                            if (pending != null)
                            {
                                ReleaseActiveNotes();
                                current = pending;
                                pending = null;
                                index = 0;
                                startTime = quantization > TimeSpan.Zero
                                    ? TimeSpan.FromTicks((now.Ticks + quantization.Ticks - 1) / quantization.Ticks * quantization.Ticks)
                                    : now;
                            }

                            if (current != null)
                            {
                                while (index < current.Length && startTime + current[index].Time <= now)
                                {
                                    Emit(current[index++].Event);
                                }

                                if (index >= current.Length)
                                {
                                    current = null;
                                }
                            }

                            if (sourceCompleted && current == null && pending == null)
                            {
                                observer.OnCompleted();
                            }
                        }
                    },
                    error =>
                    {
                        lock (gate) observer.OnError(error);
                    },
                    () =>
                    {
                        lock (gate) observer.OnCompleted();
                    });

                return new CompositeDisposable(
                    clock.SubscribeSafe(clockObserver),
                    source.SubscribeSafe(sourceObserver));
            });
        }

        readonly struct ScheduledEvent
        {
            public ScheduledEvent(TimeSpan time, MidiEvent midiEvent)
            {
                Time = time;
                Event = midiEvent;
            }

            public TimeSpan Time { get; }

            public MidiEvent Event { get; }
        }
    }
}
