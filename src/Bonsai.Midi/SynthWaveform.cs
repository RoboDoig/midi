namespace Bonsai.Midi
{
    /// <summary>
    /// Specifies the oscillator waveform used by the software synthesizer.
    /// </summary>
    public enum SynthWaveform
    {
        /// <summary>
        /// A pure sine wave.
        /// </summary>
        Sine,

        /// <summary>
        /// A triangle wave.
        /// </summary>
        Triangle,

        /// <summary>
        /// A sawtooth wave.
        /// </summary>
        Sawtooth,

        /// <summary>
        /// A square wave.
        /// </summary>
        Square
    }
}
