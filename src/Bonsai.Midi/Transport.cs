using System;
using System.ComponentModel;
using System.Reactive.Linq;

namespace Bonsai.Midi
{
    /// <summary>
    /// Represents an operator that converts a sequence of clock ticks into the musical
    /// position of a transport running at the specified tempo.
    /// </summary>
    /// <remarks>
    /// The beat position is computed from the clock time elapsed since the last tempo
    /// change, so tempo changes take effect on the next clock tick and rounding errors
    /// never accumulate. To keep multiple sequences synchronized, share a single transport
    /// between all sequence players, e.g. using a publish subject.
    /// </remarks>
    [Description("Converts a sequence of clock ticks into the musical position of a transport running at the specified tempo.")]
    public class Transport : Transform<TimeSpan, TransportState>
    {
        /// <summary>
        /// Gets or sets the tempo, in beats per minute. A tempo of zero pauses the transport.
        /// </summary>
        [Description("The tempo, in beats per minute. A tempo of zero pauses the transport.")]
        public double Tempo { get; set; } = 120;

        /// <summary>
        /// Converts each clock tick in an observable sequence into the musical position
        /// of the transport, starting at beat zero on the first tick.
        /// </summary>
        /// <param name="source">
        /// A sequence of elapsed time values, such as the ticks generated by <see cref="SequencerClock"/>.
        /// </param>
        /// <returns>A sequence of <see cref="TransportState"/> values.</returns>
        public override IObservable<TransportState> Process(IObservable<TimeSpan> source)
        {
            return Observable.Defer(() =>
            {
                var initialized = false;
                var anchorTime = TimeSpan.Zero;
                var anchorBeat = 0.0;
                var anchorTempo = 0.0;
                return source.Select(time =>
                {
                    var tempo = Math.Max(0, Tempo);
                    if (!initialized)
                    {
                        anchorTime = time;
                        anchorTempo = tempo;
                        initialized = true;
                    }
                    else if (tempo != anchorTempo)
                    {
                        anchorBeat += (time - anchorTime).TotalMinutes * anchorTempo;
                        anchorTime = time;
                        anchorTempo = tempo;
                    }

                    var beat = anchorBeat + (time - anchorTime).TotalMinutes * anchorTempo;
                    return new TransportState(time, beat, tempo);
                });
            });
        }
    }
}
